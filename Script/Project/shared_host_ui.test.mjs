import assert from 'node:assert/strict'
import { test } from 'node:test'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import { mkdir } from 'node:fs/promises'
import { createServer } from 'vite'
import { chromium } from 'playwright-core'
import { selectSharingMode } from './shared_workspace_ui_helpers.mjs'

const executablePath = process.env.EDEN_SHARED_UI_BROWSER
test('real browser: SSH trust, credential clearing, directory change, cloud creation and invitation scope', {
  skip: !executablePath, timeout: 60_000,
}, async () => {
  const root = fileURLToPath(new URL('../../frontend/web', import.meta.url))
  const output = path.resolve(process.env.EDEN_SHARED_UI_OUTPUT ?? '.artifacts/shared-host-ui')
  await mkdir(output, { recursive: true })
  const vite = await createServer({ root, cacheDir: path.join(output, 'node_modules', 'vite-' + process.pid), optimizeDeps: { entries: ['tests/fixtures/shared-workspace-page.html'] }, server: { host: '127.0.0.1', port: 0 } })
  await vite.listen()
  const browser = await chromium.launch({ executablePath, headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(`http://127.0.0.1:${vite.httpServer.address().port}/tests/fixtures/shared-workspace-page.html?state=bound&cloud`)
    await selectSharingMode(page, 'cloud')
    await page.getByRole('button', { name: '部署新云主机', exact: true }).click()
    const deploy = page.getByRole('button', { name: '部署并连接云主机', exact: true })
    assert.equal(await deploy.isDisabled(), true)
    await page.getByLabel('SSH IP 或域名', { exact: true }).fill('203.0.113.10')
    await page.getByLabel('SSH 用户名', { exact: true }).fill('fixture')
    await page.getByLabel('SSH 密码', { exact: true }).fill('preview-never-transmitted')
    const probe = page.getByRole('button', { name: '读取 SSH 主机指纹', exact: true })
    await probe.click()
    const trusted = page.getByRole('checkbox', { name: /已与云服务器控制台/ })
    await trusted.check()
    assert.equal(await deploy.isEnabled(), true)
    await page.getByLabel('SSH IP 或域名', { exact: true }).fill('203.0.113.11')
    assert.equal(await deploy.isDisabled(), true)
    await probe.click(); await trusted.check()
    await page.screenshot({ path: path.join(output, 'ssh-form-desktop.png') })
    await deploy.click()
    await page.getByRole('alert').filter({ hasText: '隔离预览不部署云服务器' }).waitFor()
    assert.equal(await page.getByLabel('SSH 密码', { exact: true }).inputValue(), '')
    await page.getByLabel('SSH 密码', { exact: true }).fill('clear-on-scope-change')
    await selectSharingMode(page, 'lan')
    await page.getByRole('button', { name: '选择共享目录…', exact: true }).first().click()
    await selectSharingMode(page, 'cloud')
    await page.waitForFunction(() => !document.querySelector('[aria-label="SSH 密码"]') || document.querySelector('[aria-label="SSH 密码"]')?.value === '')
    await page.getByRole('button', { name: '部署新云主机', exact: true }).click()
    assert.equal(await page.getByLabel('SSH 密码', { exact: true }).inputValue(), '')
    assert.equal(await deploy.isDisabled(), true)
    await page.getByRole('button', { name: '连接已有云主机', exact: true }).click()
    await page.getByLabel('管理主机', { exact: true }).selectOption('preview-cloud')
    await page.getByRole('button', { name: '为所选主机创建邀请', exact: true }).click()
    assert.match(await page.getByLabel('云主机配对邀请').inputValue(), /preview-cloud/)
    await page.getByRole('button', { name: '关闭提示', exact: true }).click()
    assert.match(await page.getByLabel('云主机配对邀请').inputValue(), /preview-cloud/)
    await page.getByRole('button', { name: '资料库', exact: true }).click()
    await page.getByRole('button', { name: '新建资料库', exact: true }).click()
    await page.getByLabel('新资料库主机').selectOption('preview-cloud')
    assert.equal(await page.getByLabel('新资料库名称').count(), 0)
    await page.getByRole('button', { name: '使用这个文件夹', exact: true }).waitFor()
    await page.waitForFunction(() => Number(getComputedStyle(document.querySelector('[aria-label="创建云端资料库"]')).opacity) > 0.99)
    await page.screenshot({ path: path.join(output, 'cloud-folder-picker-desktop.png') })
    await page.getByRole('button', { name: '使用这个文件夹', exact: true }).click()
    await page.getByLabel('新资料库名称').fill('云端界面验收资料')
    assert.equal(await page.getByRole('button', { name: '创建资料库', exact: true }).isDisabled(), true)
    await page.getByRole('checkbox', { name: /确认将所选云端目录共享/ }).check()
    await page.getByRole('button', { name: '创建资料库', exact: true }).click()
    await page.getByRole('heading', { name: '云端界面验收资料', exact: true }).waitFor()
    assert.equal(await page.locator('html').getAttribute('data-last-cloud-source'), '/srv/shared')
    await page.getByLabel('云端共享源目录', { exact: true }).getByText('/srv/shared', { exact: true }).waitFor()
    assert.equal(await page.getByRole('button', { name: '选择本机同步目录…', exact: true }).count(), 0)
    await page.screenshot({ path: path.join(output, 'cloud-source-desktop.png') })
    await page.getByText('同步到这台电脑', { exact: true }).click()
    await page.getByRole('button', { name: '选择本机同步目录…', exact: true }).waitFor()
    await page.getByRole('button', { name: '共享权限', exact: true }).click()
    await page.getByLabel('云端共享权限', { exact: true }).waitFor()
    assert.match(await page.getByLabel('云端共享权限').textContent(), /无需先选择本机同步目录/)
    await page.setViewportSize({ width: 390, height: 844 })
    await page.getByRole('button', { name: '云主机管理', exact: true }).click()
    await page.getByRole('button', { name: '部署新云主机', exact: true }).click()
    await page.waitForFunction(() => document.querySelector('[aria-label="云主机管理"]')?.getAttribute('aria-current') === 'page')
    await page.locator('[data-shared-workspace-section="network"]').evaluate(element => { element.scrollTop = 0 })
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
    await page.screenshot({ path: path.join(output, 'ssh-form-mobile.png') })
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth))
    assert.deepEqual(errors, [])
  } finally { await browser.close(); await vite.close() }
})
